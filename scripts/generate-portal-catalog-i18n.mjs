#!/usr/bin/env node
// =============================================================================
// GENERATE THE CUSTOMER PORTAL'S DECISION-CATALOGUE TRANSLATIONS
// =============================================================================
// The portal (admin/) is a separate Next.js app and cannot import from src/, so
// its copy of the catalogue is GENERATED from the same six locale files the app
// uses. Run this after touching `decisionCatalog.*` in src/i18n/locales.
//
//   node scripts/generate-portal-catalog-i18n.mjs
//
// Why the portal needs its own copy at all: `decision_items` stores the ENGLISH
// `label` and no catalog id, and `get_portal_by_access_code` returns
// `'name', di.label` and `'name', category` — so the customer's page showed the
// raw category id ("CAT_BATH_FIXTURES", uppercased by the CSS) above English
// item names, in every market including NL and DE.
//
// Items resolve by their ENGLISH label rather than an id, deliberately: that
// works for trackers ALREADY in the database, which a new id column would not.
// Exactly one English item name is ambiguous ("Underfloor Heating", in
// cat_bath_* and cat_reno_*), so the map is keyed by category id + label.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const LANGS = ['en', 'nl', 'de', 'fr', 'es', 'it'];

const load = (l) =>
  JSON.parse(fs.readFileSync(path.join(ROOT, 'src/i18n/locales', `${l}.json`), 'utf8'))
    .decisionCatalog ?? {};

const bundles = Object.fromEntries(LANGS.map((l) => [l, load(l)]));
const en = bundles.en;

// itemId -> the category it belongs to, read from the catalogue source itself.
const src = fs.readFileSync(path.join(ROOT, 'src/data/mockDecisions.ts'), 'utf8');
const itemToCategory = {};
{
  let currentCat = null;
  for (const line of src.split('\n')) {
    const c = line.match(/id:\s*'(cat_[a-z0-9_]+)'/);
    if (c) currentCat = c[1];
    const i = line.match(/id:\s*'(item_[a-z0-9_]+)'/);
    if (i && currentCat) itemToCategory[i[1]] = currentCat;
  }
}

const categoryNames = {};
const itemNames = {};
const optionLabels = {};
for (const l of LANGS) {
  categoryNames[l] = {};
  itemNames[l] = {};
  optionLabels[l] = {};
  for (const [cid, c] of Object.entries(bundles[l].categories ?? {})) {
    if (c?.name) categoryNames[l][cid] = c.name;
  }
  for (const [iid, it] of Object.entries(bundles[l].items ?? {})) {
    if (it?.name) itemNames[l][iid] = it.name;
    for (const [ov, label] of Object.entries(it?.options ?? {})) {
      if (typeof label === 'string') optionLabels[l][`${iid}.${ov}`] = label;
    }
  }
}

// "<categoryId>::<English item name>" -> itemId
const itemByEn = {};
for (const [iid, it] of Object.entries(en.items ?? {})) {
  if (!it?.name) continue;
  const cat = itemToCategory[iid] ?? '';
  itemByEn[`${cat}::${it.name}`] = iid;
  if (!(it.name in itemByEn)) itemByEn[it.name] = iid; // unambiguous fallback
}

const banner = `// GENERATED by scripts/generate-portal-catalog-i18n.mjs — DO NOT EDIT.
// Regenerate after changing decisionCatalog.* in src/i18n/locales.
// Source of truth is the app's locale files; this file only mirrors them so the
// customer portal, which cannot import from src/, can localize what it renders.
`;

const out = `${banner}
export type PortalLang = ${LANGS.map((l) => `'${l}'`).join(' | ')};

export const CATEGORY_NAMES: Record<PortalLang, Record<string, string>> = ${JSON.stringify(categoryNames, null, 2)};

export const ITEM_NAMES: Record<PortalLang, Record<string, string>> = ${JSON.stringify(itemNames, null, 2)};

export const OPTION_LABELS: Record<PortalLang, Record<string, string>> = ${JSON.stringify(optionLabels, null, 2)};

/** "<categoryId>::<English label>" -> itemId, plus unambiguous bare labels. */
export const ITEM_BY_EN: Record<string, string> = ${JSON.stringify(itemByEn, null, 2)};

/** Category heading. Falls back to whatever the RPC gave us. */
export function portalCategoryName(lang: PortalLang, categoryId: string, fallback: string): string {
  return CATEGORY_NAMES[lang]?.[categoryId] ?? CATEGORY_NAMES.en?.[categoryId] ?? fallback;
}

/** Item id from the stored ENGLISH label, disambiguated by category. */
export function portalItemId(categoryId: string, englishLabel: string): string | undefined {
  return ITEM_BY_EN[\`\${categoryId}::\${englishLabel}\`] ?? ITEM_BY_EN[englishLabel];
}

export function portalItemName(lang: PortalLang, categoryId: string, storedLabel: string): string {
  const id = portalItemId(categoryId, storedLabel);
  return (id && ITEM_NAMES[lang]?.[id]) || storedLabel;
}

/** Option labels resolve by the option's own stable \`value\` — no reverse map. */
export function portalOptionLabel(
  lang: PortalLang, categoryId: string, storedItemLabel: string,
  optionValue: string, storedOptionLabel: string,
): string {
  const id = portalItemId(categoryId, storedItemLabel);
  return (id && OPTION_LABELS[lang]?.[\`\${id}.\${optionValue}\`]) || storedOptionLabel;
}
`;

const dest = path.join(ROOT, 'admin/src/lib/decisionCatalogI18n.ts');
fs.writeFileSync(dest, out);
const n = Object.keys(itemByEn).length;
console.log(`wrote ${path.relative(ROOT, dest)} — ${Object.keys(categoryNames.en).length} categories, ${Object.keys(itemNames.en).length} items, ${Object.keys(optionLabels.en).length} option labels, ${n} reverse-map entries`);
